import { attack, box, launch, push, sphere } from "@skyzwrl/combat-builder";

export const Jab = attack("Jab")
	.startup(4)
	.active(2)
	.recovery(8)
	.hitbox(box(3, 3, 3.5).offset(0, 0, -2.5))
	.damage(4)
	.hitstun(12)
	.blockstun(8)
	.hitStop(3)
	.pushback(6)
	.knockback(push(8))
	.cancelInto("Uppercut", "Flurry")
	.build();

export const Uppercut = attack("Uppercut")
	.startup(6)
	.active(4)
	.recovery(14)
	.hitbox(box(5, 6, 4).offset(0, 1, -3))
	.damage(12)
	.chip(1)
	.hitstun(18)
	.blockstun(10)
	.hitStop(5)
	.pushback(10)
	.knockback(launch(30, 70))
	.cancelInto("GroundSlam")
	.build();

export const Flurry = attack("Flurry")
	.startup(5)
	.active(3)
	.gap(4)
	.active(3)
	.gap(4)
	.active(3)
	.recovery(16)
	.hitbox(box(4, 4, 5).offset(0, 0, -3))
	.multiHit(3, 7)
	.damage(3)
	.hitstun(14)
	.blockstun(6)
	.hitStop(2)
	.knockback(push(4))
	.build();

// the small sphere is the sweet spot right where the fists land, listed first so it wins ties
export const GroundSlam = attack("GroundSlam")
	.startup(18)
	.active(4)
	.recovery(26)
	.hitbox(sphere(3).offset(0, -2, -4), { damage: 24, knockback: launch(45, 60) })
	.hitbox(sphere(9).offset(0, -2, -4))
	.damage(14)
	.chip(3)
	.hitstun(24)
	.hitStop(7)
	.knockback(push(25))
	.guardBreak(45)
	.superArmor(6, 18)
	.parryRecoil(40)
	.build();
